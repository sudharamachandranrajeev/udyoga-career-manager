// Regenerates lib/domain/soc_index_data.dart: the job titles of the ONS SOC
// 2020 coding index (Volume 2) for health administration, electronic patient
// record and IT work, each with its SOC 2020 unit group and the ISCO-08 code
// ONS gives it. Contains public sector information licensed under the Open
// Government Licence v3.0.
//
//   dart run tool/gen_soc_index.dart [path/to/coding-index.xlsx]
//
// Without a path it downloads the index from ONS. Then run
// `dart format lib/domain/soc_index_data.dart`.
import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:http/http.dart' as http;
import 'package:xml/xml.dart';

const indexPage =
    'https://www.ons.gov.uk/methodology/classificationsandstandards/standardoccupationalclassificationsoc/'
    'soc2020/soc2020volume2codingrulesandconventions';
const indexFile =
    'https://www.ons.gov.uk/file?uri=/methodology/classificationsandstandards/standardoccupationalclassificationsoc/'
    'soc2020/soc2020volume2codingrulesandconventions/soc2020volume2thecodingindexexcel20260827v3.xlsx';

/// SOC 2020 unit groups kept: health services management and practice
/// management, IT professionals and technicians, data and business analysts,
/// IT trainers, and administrative and secretarial work.
const keep = {
  '1137', '1171', '1231', '2133', '2134', '2135', '2136', '2137', '2139', '2431', '2440', //
  '3131', '3132', '3133', '3544', '3549', '3573', '4112', '4113', '4131', '4159', '4211', '4214', '4215',
  '4216', '4217',
};

String _dart(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

/// "AB12" to its column index (AB = 27, zero based 27).
int _column(String ref) {
  var n = 0;
  for (final c in ref.replaceAll(RegExp(r'\d'), '').codeUnits) {
    n = n * 26 + (c - 64);
  }
  return n - 1;
}

Future<void> main(List<String> args) async {
  final bytes = args.isNotEmpty
      ? await File(args.first).readAsBytes()
      : (await http.get(Uri.parse(indexFile), headers: {'User-Agent': 'udyoga-tool'})).bodyBytes;
  final zip = ZipDecoder().decodeBytes(bytes);
  String read(String name) => utf8.decode(zip.findFile(name)!.content as List<int>);

  final shared = [
    for (final si in XmlDocument.parse(read('xl/sharedStrings.xml')).findAllElements('si'))
      si.findAllElements('t').map((t) => t.innerText).join(),
  ];
  // The sheet named "SOC2020 coding index", through the workbook's rels.
  final workbook = XmlDocument.parse(read('xl/workbook.xml'));
  final rid = workbook
      .findAllElements('sheet')
      .firstWhere((s) => s.getAttribute('name') == 'SOC2020 coding index')
      .attributes
      .firstWhere((a) => a.name.local == 'id')
      .value;
  final target = XmlDocument.parse(
    read('xl/_rels/workbook.xml.rels'),
  ).findAllElements('Relationship').firstWhere((r) => r.getAttribute('Id') == rid).getAttribute('Target')!;
  final sheet = XmlDocument.parse(read('xl/${target.replaceFirst(RegExp('^/?xl/'), '')}'));

  List<String> cells(XmlElement row) {
    final out = <String>[];
    for (final c in row.findElements('c')) {
      final i = _column(c.getAttribute('r')!);
      while (out.length <= i) {
        out.add('');
      }
      final v = c.getElement('v')?.innerText ?? c.findAllElements('t').map((t) => t.innerText).join();
      out[i] = c.getAttribute('t') == 's' && v.isNotEmpty ? shared[int.parse(v)] : v;
    }
    return out;
  }

  final rows = sheet.findAllElements('row').map(cells).toList();
  final head = rows.first.map((h) => h.trim()).toList();
  int col(String name) {
    final i = head.indexOf(name);
    if (i < 0) throw StateError('No column "$name" in $head');
    return i;
  }

  final soc = col('SOC_2020'), isco = col('ISCO-08 code based on SOC2020');
  final add = col('ADD'), ind = col('IND'), title = col('INDEXOCC_-_natural_word_order');
  final unit = col('SOC2020_unit_group_title');
  String at(List<String> r, int i) => i < r.length ? r[i].trim() : '';

  final seen = <String>{};
  final entries = <List<String>>[];
  final units = <String, String>{};
  for (final r in rows.skip(1)) {
    final code = at(r, soc);
    if (!keep.contains(code) || at(r, add).isNotEmpty || at(r, ind).isNotEmpty) continue;
    final t = at(r, title).toLowerCase();
    if (t.isEmpty || !seen.add('$t|$code')) continue;
    entries.add([t, code, at(r, isco)]);
    units[code] = at(r, unit);
  }
  entries.sort((a, b) => a[0].compareTo(b[0]));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_soc_index.dart from the ONS SOC 2020 coding index')
    ..writeln('// (Volume 2, file of 27 August 2026, v3): $indexPage')
    ..writeln('// Contains public sector information licensed under the Open Government Licence v3.0.')
    ..writeln('// Only titles with no industry or qualifier, in the unit groups kept by the tool.')
    ..writeln()
    ..writeln("part of 'occupations.dart';")
    ..writeln()
    ..writeln('/// SOC 2020 unit group titles.')
    ..writeln('const _socTitles = <String, String>{');
  for (final e in (units.entries.toList()..sort((a, b) => a.key.compareTo(b.key)))) {
    out.writeln('  ${_dart(e.key)}: ${_dart(e.value)},');
  }
  out
    ..writeln('};')
    ..writeln()
    ..writeln('/// (job title in lower case, SOC 2020, ISCO-08).')
    ..writeln('const _socIndex = <(String, String, String)>[');
  for (final e in entries) {
    out.writeln('  (${_dart(e[0])}, ${_dart(e[1])}, ${_dart(e[2])}),');
  }
  out.writeln('];');
  await File('lib/domain/soc_index_data.dart').writeAsString(out.toString());
  stdout.writeln('Wrote ${entries.length} titles in ${units.length} unit groups to lib/domain/soc_index_data.dart');
}
