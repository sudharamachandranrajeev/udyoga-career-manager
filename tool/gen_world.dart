// Regenerates lib/domain/world_data.dart: every ISO 3166-1 country with its
// English name, UN M49 region and subregion, current currency and official
// languages, from Unicode CLDR (cldr-json, Unicode licence).
//
//   dart run tool/gen_world.dart
//
// Then run `dart format lib/domain/world_data.dart`.
import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

const _base = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json';

/// Two-letter CLDR territories that are not ISO 3166-1 countries:
/// groupings (EU, EZ, UN, QO), pseudo-regions (XA, XB), unknown (ZZ), the
/// exceptionally reserved codes (AC, CP, DG, EA, IC, TA, CQ) and Kosovo's
/// user-assigned XK.
const _notIso = {'EU', 'EZ', 'UN', 'QO', 'XA', 'XB', 'ZZ', 'AC', 'CP', 'CQ', 'DG', 'EA', 'IC', 'TA', 'XK'};

/// Statuses CLDR gives a nationally official language.
const _official = {'official', 'de_facto_official'};

Future<Map<String, Object?>> _get(String path) async {
  final r = await http.get(Uri.parse('$_base/$path'));
  if (r.statusCode != 200) throw StateError('$path: HTTP ${r.statusCode}');
  return jsonDecode(utf8.decode(r.bodyBytes)) as Map<String, Object?>;
}

Map<String, Object?> _at(Map<String, Object?> j, List<String> path) {
  Object? v = j;
  for (final p in path) {
    v = (v as Map<String, Object?>)[p];
  }
  return v as Map<String, Object?>;
}

String _dart(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";

Future<void> main() async {
  final version = (await _get('cldr-core/package.json'))['version'];
  final names = _at(await _get('cldr-localenames-full/main/en/territories.json'), [
    'main',
    'en',
    'localeDisplayNames',
    'territories',
  ]);
  final languages = _at(await _get('cldr-localenames-full/main/en/languages.json'), [
    'main',
    'en',
    'localeDisplayNames',
    'languages',
  ]);
  final info = _at(await _get('cldr-core/supplemental/territoryInfo.json'), [
    'supplemental',
    'territoryInfo',
  ]);
  final currencies = _at(await _get('cldr-core/supplemental/currencyData.json'), [
    'supplemental',
    'currencyData',
    'region',
  ]);
  final containment = _at(await _get('cldr-core/supplemental/territoryContainment.json'), [
    'supplemental',
    'territoryContainment',
  ]);

  // Child to parent, through the plain (not "-status-") groupings only.
  final parent = <String, String>{};
  for (final e in containment.entries) {
    if (e.key.contains('-status-')) continue;
    for (final c in ((e.value as Map)['_contains'] as List).cast<String>()) {
      parent.putIfAbsent(c, () => e.key);
    }
  }
  // Each continent's countries, through every plain grouping under it.
  final children = <String, List<String>>{
    for (final e in containment.entries)
      if (!e.key.contains('-status-')) e.key: ((e.value as Map)['_contains'] as List).cast<String>(),
  };
  final continent = <String, String>{};
  void walk(String group, String name) {
    for (final c in children[group] ?? const <String>[]) {
      continent.putIfAbsent(c, () => name);
      walk(c, name);
    }
  }

  for (final c in const ['002', '019', '142', '150', '009']) {
    walk(c, names[c] as String);
  }
  String continentOf(String code) => continent[code] ?? '';

  final codes = [
    for (final k in names.keys)
      if (RegExp(r'^[A-Z]{2}$').hasMatch(k) && !_notIso.contains(k)) k,
  ]..sort();
  if (codes.length != 249) stderr.writeln('Warning: ${codes.length} countries, ISO 3166-1 has 249.');

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_world.dart from Unicode CLDR $version (cldr-json).')
    ..writeln('// Do not edit by hand: run `dart run tool/gen_world.dart`.')
    ..writeln('// Data: Unicode, Inc., Unicode licence (https://www.unicode.org/license.txt).')
    ..writeln()
    ..writeln("part of 'world.dart';")
    ..writeln()
    ..writeln('/// The CLDR release the country data came from.')
    ..writeln("const cldrVersion = '$version';")
    ..writeln()
    ..writeln('const _world = <WorldCountry>[');
  for (final c in codes) {
    final short = names['$c-alt-short'];
    var name = names[c] as String;
    if (short is String && name.contains('SAR')) name = short;
    final sub = parent[c] == null ? '' : (names[parent[c]] as String? ?? '');
    // The current legal tender: no end date, not marked as not tender.
    var currency = '';
    for (final m in (currencies[c] as List? ?? const [])) {
      final e = (m as Map).entries.first;
      final v = e.value as Map;
      if (v['_to'] == null && v['_tender'] != 'false') {
        currency = e.key as String;
        break;
      }
    }
    final pop = ((info[c] as Map?)?['languagePopulation'] as Map?) ?? const {};
    double share(Object? v) => double.tryParse('${(v as Map)['_populationPercent'] ?? 0}') ?? 0;
    final ranked = pop.entries.toList()..sort((a, b) => share(b.value).compareTo(share(a.value)));
    var langs = [
      for (final e in ranked)
        if (e.key != 'und' && _official.contains((e.value as Map)['_officialStatus'])) e.key as String,
    ];
    final official = langs.isNotEmpty;
    final spoken = ranked.where((e) => e.key != 'und');
    if (!official && spoken.isNotEmpty) langs = [spoken.first.key as String];
    final langNames = <String>[];
    for (final l in langs) {
      final base = l.split('_').first;
      final n = (languages[l] ?? languages[base] ?? l) as String;
      if (!langNames.contains(n)) langNames.add(n);
    }
    out.writeln(
      '  WorldCountry(${_dart(c)}, ${_dart(name)}, ${_dart(continentOf(c))}, ${_dart(sub)}, '
      '${_dart(currency)}, [${langNames.map(_dart).join(', ')}]${official ? '' : ', officialLanguages: false'}),',
    );
  }
  out.writeln('];');
  await File('lib/domain/world_data.dart').writeAsString(out.toString());
  stdout.writeln('Wrote ${codes.length} countries (CLDR $version) to lib/domain/world_data.dart');
}
